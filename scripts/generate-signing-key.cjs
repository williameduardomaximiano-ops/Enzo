'use strict';
const fs=require('node:fs');const crypto=require('node:crypto');const path=require('node:path');
const directory=process.argv[2];if(!directory||!path.isAbsolute(directory))throw Error('Informe uma pasta absoluta fora do repositório');
fs.mkdirSync(directory,{recursive:true,mode:0o700});
const priv=path.join(directory,'enzo-signing-private.pem'),pub=path.join(directory,'enzo-signing-public.pem');
if(fs.existsSync(priv)||fs.existsSync(pub))throw Error('Chaves já existem; não substituir');
const pair=crypto.generateKeyPairSync('ed25519');
fs.writeFileSync(priv,pair.privateKey.export({type:'pkcs8',format:'pem'}),{mode:0o600,flag:'wx'});
fs.writeFileSync(pub,pair.publicKey.export({type:'spki',format:'pem'}),{mode:0o600,flag:'wx'});
console.log('Chaves criadas. Guarde o arquivo privado fora do GitHub, em local seguro.');
